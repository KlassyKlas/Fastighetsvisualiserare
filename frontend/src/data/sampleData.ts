function makePropertyPolygon(lng: number, lat: number): GeoJSON.Polygon {
  const dLng = 0.003;
  const dLat = 0.002;
  return {
    type: 'Polygon',
    coordinates: [
      [
        [lng - dLng / 2, lat - dLat / 2],
        [lng + dLng / 2, lat - dLat / 2],
        [lng + dLng / 2, lat + dLat / 2],
        [lng - dLng / 2, lat + dLat / 2],
        [lng - dLng / 2, lat - dLat / 2],
      ],
    ],
  };
}

